"""Synthetic OHLCV fixtures.

These series are generated by a random number generator so tests can check program
behaviour. They are not market records and the application never loads this module.
"""

from __future__ import annotations

import numpy as np
import pandas as pd


def make_ohlcv(n: int = 120, seed: int = 7, start: str = "2022-01-03") -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    returns = rng.normal(0.0, 0.012, n)
    close = 250 * np.cumprod(1 + returns)
    open_ = np.empty(n)
    open_[0] = close[0]
    open_[1:] = close[:-1]
    high = np.maximum(open_, close) * (1 + rng.uniform(0.001, 0.01, n))
    low = np.minimum(open_, close) * (1 - rng.uniform(0.001, 0.01, n))
    volume = rng.integers(500_000, 5_000_000, n).astype(float)
    return pd.DataFrame(
        {
            "Date": pd.bdate_range(start, periods=n),
            "Open": open_,
            "High": high,
            "Low": low,
            "Close": close,
            "Adj Close": close * 0.99,
            "Volume": volume,
        }
    )
